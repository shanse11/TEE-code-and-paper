    doc = Document(str(OUT))

    for idx, paragraph in enumerate(doc.paragraphs):
        new_text = paragraph_updates.get(idx, paragraph.text)
        new_text = normalize_text(new_text)
        if new_text != paragraph.text:
            set_paragraph_text(paragraph, new_text)

    for table in doc.tables:
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        for row in table.rows:
            for cell in row.cells:
                cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
                for paragraph in cell.paragraphs:
                    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    new_text = normalize_text(paragraph.text)
                    if new_text != paragraph.text:
                        set_paragraph_text(paragraph, new_text)

    for table_idx, row_idx, col_idx in table_updates:
        doc.tables[table_idx].rows[row_idx].cells[col_idx].text = table_updates[(table_idx, row_idx, col_idx)]

    # Final cautious term cleanup in cells and paragraphs.
