s(8, f"高频去中心化应用的困难并不只是吞吐量不足。此类应用的单次交互价值通常不高，却要求持续状态更新、低延迟反馈、低链上负担，以及异常场景下的公开可验证仲裁。以链上 AI 推理服务为例，用户连续提交提示，执行者在可信执行环境中生成响应，并向链上提交紧凑提交；完整提示、响应与证明保存在数据可用性层。正常路径需要尽量轻量，但异常路径必须具备足够的可验证性：当响应与数据可用性负载不一致，或挑战在中途超时时，系统不能仅报告{LQ}异常已检测{RQ}，还需要保证争议能够继续推进到重放与结算。")

s(9, f"现有路线分别缓解了上述矛盾的一部分，但难以同时满足低成本、低延迟、公开可验证和挑战活性四项要求。全链上执行保留了公开验证能力，却将高频负载、存储和执行成本直接推到链上；完全链下执行降低了延迟和成本，却缺少用户可依赖的公开仲裁路径；纯 TEE 执行可以降低正常路径的验证成本，但系统安全性和可用性仍受硬件、宿主输入输出、远程证明以及服务连续性的影响。混合 TEE 汇总的优势在于将 TEE 快速路径与链上异常路径结合起来；相应地，其关键风险也在异常路径：如果缺少恢复机制和证据入口，系统可能在最需要仲裁时失去协议连续性。")

s(10, f"超时后挑战流程卡死并非普通工程异常，而是协议活性与仲裁连续性问题。传统挑战机制可以关注错误是否能够被发现，但对于高频去中心化应用而言，检测只是争议处理的起点：未完成的挑战会占用状态、延迟结算，并使错误提交停留在不可结算的中间状态。因此，本文以{LQ}故障发生、恢复、重放、仲裁结算{RQ}为主线。异常被观察后，协议需要恢复挑战会话；恢复后，紧凑提交必须能够指向重放所需证据；重放之后，仲裁结果才能进入结算或惩罚。")

s(11, f"轻量提交同样存在安全语义边界。若紧凑提交只是普通哈希，虽然能够压缩链上字节，却无法指明验证者如何取回负载、验证字段级成员证明，或为重放构造证据上下文。本文将紧凑提交视为最小可验证证据入口：它在正常路径保持链上提交轻量，在异常路径仍能回指数据可用性负载、Merkle 证明、证明摘要和执行摘要。实验部分采用合成负载、模拟 TEE、可验证数据可用性注册表、本地以太坊虚拟机燃料实测与 Sepolia 可部署性证据；这些证据用于评估机制接口与趋势，而非声称生产网络性能。")

